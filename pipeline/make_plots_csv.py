# Study-area bounding box used to screen transcription and source typos.
BOX = (33.80, 34.15, 36.20, 36.45)


def verify(rows):
    """Flag any plot outside the delta bounding box."""
    bad = [r for r in rows
           if not (BOX[0] <= r["lon"] <= BOX[1] and BOX[2] <= r["lat"] <= BOX[3])]
    for r in bad:
        print(f"  [outside box] plot {r['plot']} ({r['association']}): "
              f"{r['lat']:.5f} N, {r['lon']:.5f} E", file=sys.stderr)
    return bad


def main():
    rows = []
    for (group, subtype, assoc), plots in DATA.items():
        for p, size, alt, date, la_d, la_m, lo_d, lo_m in plots:
            rows.append({
                "plot": p, "group": group, "subtype": subtype,
                "association": assoc, "size_m2": size, "altitude": alt,
                "date": date,
                "lat": la_d + la_m / 60.0, "lon": lo_d + lo_m / 60.0,
            })

    print(f"transcribed {len(rows)} plots")
    for g in ("halophytic", "dune", "aquatic"):
        print(f"  {g:11s} {sum(r['group'] == g for r in rows):3d}")

    bad = verify(rows)
    print(f"outside study-area box: {len(bad)} (excluded from the CSV)")
    rows = [r for r in rows if r not in bad]

    with open("reference_plots.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote reference_plots.csv with {len(rows)} plots")


if __name__ == "__main__":
    main()
